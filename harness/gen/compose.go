package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/DawnBreather/tmux-hub/internal/conf"
)

// Out is everything a topology becomes. Generate is total — Load has already refused anything
// that could not be realised — so nothing here can fail halfway and leave a fleet that half
// exists.
type Out struct {
	// Compose is the compose file. Every per-machine decision is IN it, as the service's own
	// start-up command: which host keys are generated, which credentials are installed, which
	// interface carries which delay. That is deliberate. The alternative is an entrypoint
	// script in the image reading environment variables, and then the generated artefact
	// records none of the choices it made — a diff of the compose is the review.
	Compose string
	// Files are the text artefacts, keyed by path relative to the output directory.
	Files map[string]string
	// Keys are the keypairs the CLI must generate into `keys/`. They are never committed: the
	// repository is public and a secret scanner should fire on a key inside it (spec §4.2).
	Keys []string
}

// The account every ssh session lands as. uid 1000 mirrors the live fleet, where the remote
// uid decides both the tmux socket path and which `~/.claude` is read (spec §3.1).
const (
	account = "dev"
	home    = "/home/" + account
)

// Generate turns a declared topology into the fleet that realises it.
func Generate(top Topology) Out {
	out := Out{Files: map[string]string{}}

	subnet := map[string]string{}
	for i, n := range top.Networks {
		subnet[n] = fmt.Sprintf("10.99.%d", i+1)
	}
	octet := map[string]int{}
	for i, m := range top.Machines {
		octet[m.ID] = 10 + i
	}
	address := func(machine, network string) string {
		return fmt.Sprintf("%s.%d", subnet[network], octet[machine])
	}

	byID := map[string]Machine{}
	owner := map[string]string{} // alias -> machine id
	for _, m := range top.Machines {
		byID[m.ID] = m
		for _, a := range m.Aliases {
			owner[a] = m.ID
		}
	}

	// presents[declarer][target] is the keypair the declarer offers when it opens a connection:
	// the edge's key when an edge names one, its own otherwise. This one map decides the whole
	// Ready/Blocked distinction, so it is computed once and read by both halves below —
	// identities on the near side, authorized_keys on the far side. Two copies of it would
	// drift into a leaf that authorises a key nobody holds, which reads as a broken fixture.
	presents := map[string]map[string]string{}
	for _, m := range top.Machines {
		presents[m.ID] = map[string]string{}
		for _, d := range m.Declares {
			presents[m.ID][owner[d]] = m.ID
		}
	}
	for _, e := range top.Edges {
		if e.Key != "" {
			presents[e.From][e.To] = e.Key
		}
	}

	keys := map[string]bool{}
	for _, m := range top.Machines {
		keys[m.ID] = true
	}
	for _, e := range top.Edges {
		if e.Key != "" {
			keys[e.Key] = true
		}
	}
	out.Keys = keysOf(keys)

	for _, m := range top.Machines {
		if cfg := sshConfig(m, byID, presents[m.ID]); cfg != "" {
			out.Files["ssh/"+m.ID+"/config"] = cfg
		}
		if m.Hub {
			out.Files["ssh/"+m.ID+"/hosts.toml"] = hubHosts(m)
		}
	}

	out.Files["fleet.json"] = fleetJSON(top)
	out.Compose = compose(top, subnet, address, byID, presents)
	return out
}

// fleetJSON publishes what was built, for the consumers that cannot import this command because
// it is `package main`: the harness's own self-test, which has to know which observer can reach
// which machine and with whose key, and later the oracle comparing a derived graph against the
// declared topology. Without it each of those restates the topology by hand, and a restated
// fixture is one that stops matching the moment a row is added.
func fleetJSON(top Topology) string {
	raw, err := json.MarshalIndent(top, "", "  ")
	if err != nil {
		// Unreachable: every field is a string, a bool or a slice of strings. Panicking rather
		// than returning an error keeps Generate total, which is what lets Load own every refusal.
		panic("harness/gen: the topology does not marshal: " + err.Error())
	}
	return string(raw) + "\n"
}

// sshConfig writes what `ssh -G` on this machine will answer for every alias it declares. It
// is the artefact the discovery reads over a hop, and the `IdentityFile` line is what the
// Blocked diagnosis is derived from.
//
// A machine that declares nothing gets NO file, not an empty one: `nuc` measured, it has no
// `~/.ssh/config` at all, and "the hop offers nothing" has to be distinguishable from "the hop
// offers an empty list" or a reader cannot report which happened.
func sshConfig(m Machine, byID map[string]Machine, presents map[string]string) string {
	if !m.HasSSHConfig() {
		return ""
	}
	var b strings.Builder
	b.WriteString("# GENERATED by harness/gen — do not edit.\n")
	for _, alias := range m.Declares {
		var target Machine
		for _, cand := range byID {
			for _, a := range cand.Aliases {
				if a == alias {
					target = cand
				}
			}
		}
		fmt.Fprintf(&b, "\nHost %s\n", alias)
		// HostName is the machine's id, which is its compose service name and therefore what
		// the container network resolves. It is per-MACHINE rather than per-alias on purpose:
		// two aliases for one machine must reach one machine, or the identity merge the
		// topology exists to exercise has nothing to merge.
		fmt.Fprintf(&b, "    HostName %s\n", target.ID)
		fmt.Fprintf(&b, "    User %s\n", account)
		fmt.Fprintf(&b, "    IdentityFile ~/.ssh/%s\n", presents[target.ID])
		b.WriteString("    IdentitiesOnly yes\n")
		// The host keys do not exist until the container starts (spec §2.3), so they cannot be
		// pre-seeded into known_hosts and this is the only setting that can work. It is a
		// property of the fixture, stated in harness/README.md, not of the product.
		b.WriteString("    StrictHostKeyChecking accept-new\n")
		fmt.Fprintf(&b, "    UserKnownHostsFile %s/.ssh/known_hosts\n", home)
	}
	return b.String()
}

// hubHosts is the hop's own `hosts.toml`. A hop's hub config RANKS; it never creates
// (spec §3.2 invariant 6), so it lists what that hop already declares in ssh and nothing else.
func hubHosts(m Machine) string {
	var b strings.Builder
	b.WriteString("# GENERATED by harness/gen — do not edit.\n")
	for _, alias := range m.Declares {
		b.WriteString("\n[[host]]\n")
		fmt.Fprintf(&b, "alias = %s\n", conf.Quote(alias))
		b.WriteString("enabled = true\n")
	}
	return b.String()
}

func compose(top Topology, subnet map[string]string, address func(string, string) string,
	byID map[string]Machine, presents map[string]map[string]string) string {

	// delays[machine][network] — a delay is realised as netem on ONE interface, and Load has
	// already refused a second claim on the same one.
	delays := map[string]map[string]string{}
	for _, e := range top.Edges {
		if e.Delay == "" {
			continue
		}
		link := shared(byID[e.From].Networks, byID[e.To].Networks)[0]
		if delays[e.To] == nil {
			delays[e.To] = map[string]string{}
		}
		// The qdisc goes on the FAR end's interface, not the near end's, because netem delays
		// what leaves an interface: on the far end it delays exactly the replies to this edge,
		// so the declared delay is the round trip an observer measures. On the near end it
		// would also delay every other machine on that network — root -> hop would slow the
		// twins, which declare no delay at all.
		delays[e.To][link] = e.Delay
	}

	var b strings.Builder
	b.WriteString("# GENERATED by harness/gen from harness/topology/" + top.Name + ".toml — do not edit.\n")
	b.WriteString("#\n")
	b.WriteString("# Regenerate with: go run ./harness/gen -topology harness/topology/" + top.Name + ".toml\n")
	fmt.Fprintf(&b, "name: harness-%s\n", top.Name)

	b.WriteString("\nnetworks:\n")
	for _, n := range top.Networks {
		fmt.Fprintf(&b, "  %s:\n", n)
		b.WriteString("    driver: bridge\n")
		b.WriteString("    ipam:\n")
		b.WriteString("      config:\n")
		fmt.Fprintf(&b, "        - subnet: %s.0/24\n", subnet[n])
		fmt.Fprintf(&b, "          gateway: %s.1\n", subnet[n])
	}

	b.WriteString("\nservices:\n")
	for _, m := range top.Machines {
		fmt.Fprintf(&b, "  %s:\n", m.ID)
		b.WriteString("    build:\n")
		b.WriteString("      context: ../image\n")
		b.WriteString("      args:\n")
		fmt.Fprintf(&b, "        BASE: %s\n", m.Base())
		fmt.Fprintf(&b, "        SHELL_KIND: %s\n", m.Shell)
		fmt.Fprintf(&b, "        TMUX: %q\n", m.Tmux)
		// hostname is the machine's OWN idea of its name, which is how two different machines
		// come to answer to one hostname (four `web-ws` on the live tailnet).
		hostname := m.Hostname
		if hostname == "" {
			hostname = m.ID
		}
		fmt.Fprintf(&b, "    hostname: %s\n", hostname)
		if len(delays[m.ID]) > 0 {
			// The capability is granted exactly where a qdisc is applied, by the same branch, so
			// a delay cannot be declared without the right to apply it.
			b.WriteString("    cap_add:\n")
			b.WriteString("      - NET_ADMIN\n")
		}
		b.WriteString("    volumes:\n")
		b.WriteString("      - ./keys:/harness/keys:ro\n")
		if m.HasMaterial() {
			fmt.Fprintf(&b, "      - ./ssh/%s:/harness/ssh:ro\n", m.ID)
		}
		b.WriteString("    networks:\n")
		for _, n := range m.Networks {
			fmt.Fprintf(&b, "      %s:\n", n)
			fmt.Fprintf(&b, "        ipv4_address: %s\n", address(m.ID, n))
			if m.Hostname != "" && m.Hostname != m.ID {
				// A network alias several containers share resolves to any of them, which is
				// precisely the collision this row exists to reproduce.
				b.WriteString("        aliases:\n")
				fmt.Fprintf(&b, "          - %s\n", m.Hostname)
			}
		}
		b.WriteString("    healthcheck:\n")
		b.WriteString("      test: [\"CMD-SHELL\", \"ss -ltn | grep -q ':22 '\"]\n")
		b.WriteString("      interval: 1s\n")
		b.WriteString("      timeout: 2s\n")
		b.WriteString("      retries: 60\n")
		b.WriteString("    command:\n")
		b.WriteString("      - /bin/sh\n")
		b.WriteString("      - -c\n")
		b.WriteString("      - |\n")
		for _, line := range startup(m, top, byID, presents, delays[m.ID], address) {
			// Compose interpolates `$VAR` in a command string BEFORE the container sees it, so an
			// unescaped shell variable arrives as the empty string. Measured on Compose 5.1.4:
			// `tc qdisc replace dev "$iface" …` came out of `docker compose config` as
			// `dev ""` — the whole delay silently gone — and `config` still answered rc=0, with
			// nothing but a warning on stderr that nobody reads in a script. `$$` is compose's
			// own escape and the container receives one `$`.
			//
			// Every `$` is doubled here, at the one place shell text enters the file, rather than
			// at each site that writes one: `$(` and `$4` happen to survive un-escaped today
			// because neither is a valid variable reference, and a rule with exceptions is a rule
			// the next line of shell forgets.
			b.WriteString("        " + strings.ReplaceAll(line, "$", "$$") + "\n")
		}
	}
	return b.String()
}

// startup is the service's own start-up, line by line. It is generated rather than shipped in
// the image because the image must be ONE image: every per-machine choice lives here, where the
// generated compose records it.
func startup(m Machine, top Topology, byID map[string]Machine,
	presents map[string]map[string]string, delays map[string]string,
	address func(string, string) string) []string {

	lines := []string{"set -e"}

	// This is the property the whole fixture rests on: a host key baked into the image would
	// give every container ONE identity, the derived graph would collapse to a single node, and
	// the fixture would then encode the belief that a fleet is a fleet (spec §2.3).
	lines = append(lines,
		"# Host keys, per container, at start-up. A key baked into the image would give every",
		"# machine one identity and the whole graph would collapse to a single node.",
		"#",
		"# The refusal below is not belt-and-braces. Installing openssh-server GENERATES host keys",
		"# in the image layer (measured on debian:13), and `ssh-keygen -A` only creates the ones",
		"# that are missing — so a key surviving into the image is silently honoured here and the",
		"# whole fleet becomes one machine. This turns that into a fleet that refuses to start.",
		"if [ -e /etc/ssh/ssh_host_ed25519_key ]; then",
		"  echo \"a host key came from the image, so every container would share one identity;\" >&2",
		"  echo \"the image must run: rm -f /etc/ssh/ssh_host_* after installing openssh-server\" >&2",
		"  exit 1",
		"fi",
		"ssh-keygen -A",
		"mkdir -p /run/sshd "+home+"/.ssh")

	// Credentials. The near side installs what it presents; the far side authorises what its
	// declarers present to it. Both come from one map, so they cannot disagree.
	var identities []string
	for _, k := range presents[m.ID] {
		if !contains(identities, k) {
			identities = append(identities, k)
		}
	}
	sort.Strings(identities)
	for _, k := range identities {
		lines = append(lines, fmt.Sprintf("cp /harness/keys/%s %s/.ssh/%s", k, home, k))
	}

	var authorised []string
	for _, d := range top.Machines {
		k, declared := presents[d.ID][m.ID]
		if !declared {
			continue
		}
		// A declaration only reaches a machine it shares a network with. Authorising a key that
		// could never arrive would make an unreachable machine look credentialled.
		if len(shared(d.Networks, m.Networks)) == 0 {
			continue
		}
		if !contains(authorised, k) {
			authorised = append(authorised, k)
		}
	}
	sort.Strings(authorised)
	lines = append(lines, ": > "+home+"/.ssh/authorized_keys")
	for _, k := range authorised {
		lines = append(lines, fmt.Sprintf("cat /harness/keys/%s.pub >> %s/.ssh/authorized_keys", k, home))
	}
	// One predicate decides whether the file exists and whether the start-up copies it. Two
	// would drift into a `cp` of a file the generator did not write, which is a container that
	// dies at start-up for a reason that names no cause.
	if m.HasSSHConfig() {
		lines = append(lines, "cp /harness/ssh/config "+home+"/.ssh/config")
	}
	if m.Hub {
		lines = append(lines,
			"mkdir -p "+home+"/.config/tmux-hub",
			"cp /harness/ssh/hosts.toml "+home+"/.config/tmux-hub/hosts.toml")
	}
	lines = append(lines,
		"chown -R "+account+":"+account+" "+home+"/.ssh",
		"chmod 700 "+home+"/.ssh",
		"chmod 600 "+home+"/.ssh/*")

	for _, n := range m.Networks {
		delay, ok := delays[n]
		if !ok {
			continue
		}
		addr := address(m.ID, n)
		lines = append(lines,
			fmt.Sprintf("# The %s delay declared on the %s link, applied to the interface that", delay, n),
			"# holds this machine's address on it. netem acts on what LEAVES an interface, so on",
			"# this end the replies are what is held back, and the declared figure is the round trip.",
			fmt.Sprintf("iface=$(ip -o -4 addr show | awk '$4 ~ /^%s\\// {print $2; exit}')",
				strings.ReplaceAll(addr, ".", "\\.")),
			fmt.Sprintf("test -n \"$iface\" || { echo \"no interface holds %s — the %s delay cannot be applied; check the network's subnet\" >&2; exit 1; }",
				addr, delay),
			// `replace` rather than `add`, so a `docker compose restart` does not fail on the
			// qdisc its own previous run installed.
			fmt.Sprintf("tc qdisc replace dev \"$iface\" root netem delay %s", delay))
	}

	return append(lines, "exec /usr/sbin/sshd -D -e")
}
